export function lookupMasterMedicineByBarcode(barcode: string): MasterMedicine | null {
  if (!barcode) return null;
  const clean = barcode.trim();
  const directMatch = MASTER_MEDICINES.find(m => m.barcode === clean);
  if (directMatch) return directMatch;

  // Suffix or prefix match
  const partialMatch = MASTER_MEDICINES.find(m => 
    clean.includes(m.barcode) || m.barcode.includes(clean)
  );
  if (partialMatch) return partialMatch;

  return null;
}
